#!/usr/bin/env python3
"""Builds the Resolved Logic site.

Reads the page files in src/pages, wraps them in src/layout.html, fills in the
header and footer from src/partials, and pulls case studies and shared copy
from the TOML files in src/data. Writes finished .html files into the repo
root, which is what GitHub Pages serves.

    python build.py

Needs Python 3.11 or newer and nothing else.
"""
import html
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).parent
SRC = ROOT / "src"
BANNER = "<!-- Generated by build.py from src/. Edit the files in src/, not this one. -->\n"


def esc(text):
    return html.escape(str(text), quote=True)


def load(name):
    with open(SRC / "data" / f"{name}.toml", "rb") as f:
        return tomllib.load(f)


# ---------------------------------------------------------------- pieces

def split_label(item):
    """'Label: text' becomes a bold label plus text."""
    head, sep, tail = item.partition(": ")
    if sep and len(head) < 48:
        return f"<b>{esc(head)}</b> {esc(tail)}"
    return esc(item)


def short_title(project):
    return project["title"].split(" — ")[0]


def render_stats(stats):
    return "".join(
        f'<div class="stat"><strong>{esc(s["value"])}</strong>{esc(s["label"])}</div>' for s in stats
    )


def render_pills(stats):
    if not stats:
        return ""
    pills = "".join(f'<span class="pill"><strong>{esc(s["value"])}</strong> {esc(s["label"])}</span>' for s in stats)
    return f'<div class="pills">{pills}</div>'


def render_project(p, index):
    num = f"{index + 1:02d}"
    flagship = p.get("flagship", False)
    title = esc(p["title"])
    if p.get("url"):
        title = (f'<a href="{esc(p["url"])}" target="_blank" rel="noopener">{title}'
                 f'<span class="ext" aria-hidden="true">&nearr;</span></a>')
    chips = f'<span class="chip">{esc(p["tag"])}</span>'
    if p.get("status"):
        chips += f'<span class="chip live">{esc(p["status"])}</span>'
    if flagship:
        chips += '<span class="chip live">Flagship</span>'
    xform = (f'<p class="xform"><span class="f">{esc(p["from"])}</span><span class="a">&rarr;</span>'
             f'<span class="t">{esc(p["to"])}</span></p>')
    blocks = '<div class="blocks">' + "".join(
        f"<div><h4>{label}</h4><p>{esc(p[key])}</p></div>"
        for key, label in (("problem", "Problem"), ("logic", "Logic"), ("result", "Result"))
        if p.get(key)
    ) + "</div>"

    features = "".join(
        f'<div><h4>{esc(f["heading"])}</h4><ul>' + "".join(f"<li>{split_label(i)}</li>" for i in f["items"]) + "</ul></div>"
        for f in p.get("features", [])
    )
    shots = ""
    if p.get("images"):
        shots = '<div class="shots" aria-label="Screenshots">' + "".join(
            f'<a href="{esc(i["src"])}" target="_blank" rel="noopener">'
            f'<img src="{esc(i["src"])}" alt="{esc(p["title"])}: {esc(i["alt"])}" loading="lazy"></a>'
            for i in p["images"]
        ) + "</div>"
    more_open = "Hide the full feature set" if flagship else "Hide the details"
    more_closed = "View the full feature set" if flagship else "View technical and human features"
    details = ""
    if features or shots:
        details = (f'<details class="more"><summary><span class="when-closed">{more_closed}</span>'
                   f'<span class="when-open">{more_open}</span></summary>'
                   f'<div class="detail">{features}</div>{shots}</details>')

    if flagship:
        cover = ""
        if p.get("cover"):
            host = re.sub(r"^https?://", "", p.get("url", "")).rstrip("/")
            cover = (f'<div class="browser"><div class="browser-bar"><i></i><i></i><i></i><span>{esc(host)}</span></div>'
                     f'<img src="{esc(p["cover"])}" alt="{esc(p["title"])} homepage" width="1000" height="634"></div>')
        return (f'<article class="proj flag"><div class="flag-top"><div>'
                f'<div class="proj-meta"><span class="proj-num">{num}</span>{chips}</div>'
                f'<h2 class="proj-title">{title}</h2>{xform}'
                f'<div class="stats">{render_stats(p.get("stats", []))}</div></div>'
                f'<div>{blocks}</div></div>{cover}{details}</article>')
    return (f'<article class="proj"><div class="proj-num">{num}</div><div>'
            f'<div class="proj-meta">{chips}</div><h2 class="proj-title">{title}</h2>{xform}'
            f'{blocks}{render_pills(p.get("stats", []))}{details}</div></article>')


def build_blocks(site, content, projects):
    flagship = next((p for p in projects if p.get("flagship")), projects[0])
    ledger = "".join(
        f'<div class="ledger-row"><div class="ledger-from">{esc(p["from"])}</div>'
        f'<div class="ledger-to"><span>&rarr;</span>{esc(p["to"])}</div>'
        f'<div class="ledger-proj">{esc(short_title(p))}</div></div>'
        for p in projects if p.get("ledger")
    )

    def steps(kind):
        out = []
        for i, s in enumerate(content["step"], 1):
            out.append(
                f'<div class="step"><div class="step-state"><span>{i:02d}</span><span>{esc(s["state"])}</span></div>'
                f'<svg class="thread" data-seed="{30 + i}" data-n="8" data-h="64" data-mult="{s["tangle"]}" aria-hidden="true"></svg>'
                f'<h3>{esc(s["title"])}</h3><p>{esc(s[kind])}</p></div>'
            )
        return "".join(out)

    if (ROOT / "static" / "img" / "portrait.jpg").exists():
        portrait = ('<div class="portrait"><img src="static/img/portrait.jpg" alt="Portrait" '
                    'width="800" height="1000"></div>')
    else:
        portrait = ('<div class="portrait" aria-label="Photo placeholder">'
                    '<svg class="thread on-ink" data-seed="5" data-n="22" data-h="500" data-mult="0.9" data-dark="1" aria-hidden="true"></svg>'
                    '<div class="portrait-note"><strong>Your photo goes here</strong>'
                    'Save a portrait as static/img/portrait.jpg and run build.py. It replaces this panel.</div></div>')

    return {
        "portrait": portrait,
        "projects":"".join(render_project(p, i) for i, p in enumerate(projects)),
        "project_count": f"{len(projects):02d}",
        "ledger": ledger,
        "flagship_stats": render_stats(flagship.get("stats", [])),
        "flagship_cover": esc(flagship.get("cover", "")),
        "flagship_url": esc(flagship.get("url", "")),
        "flagship_host": esc(re.sub(r"^https?://", "", flagship.get("url", "")).rstrip("/")),
        "steps_short": steps("short"),
        "steps_long": steps("long"),
        "values": "".join(
            f'<div class="value"><h3>{esc(v["title"])}</h3><p>{esc(v["text"])}</p></div>' for v in content["value"]),
        "capabilities": "".join(
            f'<div class="cap"><strong>{esc(c["title"])}</strong><span>{esc(c["text"])}</span></div>'
            for c in content["capability"]),
    }


def render_nav(site, active):
    links = []
    for item in site["nav"]:
        current = ' aria-current="page"' if item["key"] == active else ""
        if item.get("button"):
            cls = "btn"
        else:
            cls = "nl active" if item["key"] == active else "nl"
        links.append(f'<a class="{cls}" href="{item["href"]}"{current}>{esc(item["label"])}</a>')
    return "\n      ".join(links)


# ---------------------------------------------------------------- templating

def parse_page(path):
    raw = path.read_text(encoding="utf-8")
    meta, body = {}, raw
    m = re.match(r"---\s*\n(.*?)\n---\s*\n", raw, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
        body = raw[m.end():]
    return meta, body


def fill(template, context, where):
    def repl(match):
        key = match.group(1)
        value = context
        for part in key.split("."):
            if not isinstance(value, dict) or part not in value:
                raise SystemExit(f"Unknown placeholder {{{{ {key} }}}} in {where}")
            value = value[part]
        return str(value)
    return re.sub(r"\{\{\s*([\w.]+)\s*\}\}", repl, template)


def main():
    site, content, projects = load("site"), load("content"), load("projects")["project"]
    blocks = build_blocks(site, content, projects)
    layout = (SRC / "layout.html").read_text(encoding="utf-8")
    partials = {p.stem: p.read_text(encoding="utf-8") for p in (SRC / "partials").glob("*.html")}
    written = []

    for page in sorted((SRC / "pages").glob("*.html")):
        meta, body = parse_page(page)
        out_name = page.name
        for required in ("title", "description"):
            if required not in meta:
                raise SystemExit(f"{page.name} is missing '{required}:' in its header")
        page_scripts = "".join(
            f'\n<script src="{s.strip()}" defer></script>' for s in meta.get("scripts", "").split(",") if s.strip())
        canonical = site["url"] + ("/" if out_name == "index.html" else "/" + out_name)
        context = {
            "site": {k: esc(v) for k, v in site.items() if not isinstance(v, (list, dict))},
            "page": {k: esc(v) for k, v in meta.items()},
            **blocks,
            "nav": render_nav(site, meta.get("nav", "")),
            "page_scripts": page_scripts,
            "canonical": canonical,
            "year": site["copyright_year"],
        }
        for name, text in partials.items():
            context["partial_" + name] = fill(text, context, f"partial {name}")
        context["content"] = fill(body, context, page.name)
        html_out = fill(layout, context, "layout.html")
        (ROOT / out_name).write_text(BANNER + html_out, encoding="utf-8")
        written.append(out_name)

    for r in site.get("redirect", []):
        stub = (f'<!DOCTYPE html>\n<html lang="en"><head><meta charset="UTF-8">'
                f'<title>Redirecting</title><meta http-equiv="refresh" content="0; url={r["to"]}">'
                f'<link rel="canonical" href="{site["url"]}/{"" if r["to"] == "index.html" else r["to"]}">'
                f'<meta name="robots" content="noindex"></head>'
                f'<body><p>This page has moved to <a href="{r["to"]}">{r["to"]}</a>.</p></body></html>\n')
        (ROOT / r["from"]).write_text(BANNER + stub, encoding="utf-8")
        written.append(r["from"])

    print("Built:", ", ".join(written))


if __name__ == "__main__":
    sys.exit(main())
